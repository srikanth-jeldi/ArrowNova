"""Prepare local iOS signing/ads configuration without modifying shared IDs."""
import argparse
import json
import plistlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEST_APP = "ca-app-pub-3940256099942544~1458002511"
ANDROID_UNITS = {"ca-app-pub-9061518700917881/4239172993",
                 "ca-app-pub-9061518700917881/1696855854",
                 "ca-app-pub-9061518700917881/4798496062"}
UNIT_KEYS = ("IOS_BANNER_ID", "IOS_INTERSTITIAL_ID", "IOS_REWARDED_ID")


def validate_ads(data):
    for key in ("ADMOB_APP_ID",) + UNIT_KEYS:
        value = data.get(key, "")
        separator = "~" if key == "ADMOB_APP_ID" else "/"
        if not isinstance(value, str) or not re.fullmatch(
                r"ca-app-pub-\d{16}" + separator + r"\d{10}", value):
            raise ValueError(f"{key}: enter a real iOS AdMob ID (separator {separator}).")
        if "3940256099942544" in value or value in ANDROID_UNITS:
            raise ValueError(f"{key}: Google test IDs and existing Android IDs cannot be used for store mode.")
    if len({data[key] for key in UNIT_KEYS}) != 3:
        raise ValueError("Banner, interstitial and rewarded units must be different IDs.")
    if len({data[key].split('~')[0].split('/')[0] for key in ("ADMOB_APP_ID",) + UNIT_KEYS}) != 1:
        raise ValueError("All four IDs must belong to the same AdMob publisher account.")
    return data


def configure(mode, team, root=ROOT):
    if not re.fullmatch(r"[A-Z0-9]{10}", team):
        raise ValueError("Team ID must be the 10-character Apple Developer Team ID, not an email.")
    data = {"ADMOB_APP_ID": TEST_APP}
    if mode == "store":
        config = root / "ios/ads.ios.local.json"
        if not config.exists():
            raise ValueError("Copy ios/ads.ios.example.json to ios/ads.ios.local.json and fill in all four iOS IDs.")
        data = validate_ads(json.loads(config.read_text(encoding="utf-8-sig")))
    generated = root / ".build-tmp/ios"
    generated.mkdir(parents=True, exist_ok=True)
    flutter = root / "ios/Flutter"
    flutter.mkdir(parents=True, exist_ok=True)
    (flutter / "Ads.local.xcconfig").write_text(
        "// Generated by tool/ios_release.py\nADMOB_APP_ID=" + data["ADMOB_APP_ID"] + "\n", encoding="utf-8")
    (flutter / "Signing.local.xcconfig").write_text(
        "// Generated by tool/ios_release.py\nDEVELOPMENT_TEAM=" + team + "\nCODE_SIGN_STYLE=Automatic\n", encoding="utf-8")
    defines = {"LIVE_ADS": mode == "store"}
    if mode == "store":
        defines.update({key: data[key] for key in UNIT_KEYS})
    (generated / "defines.json").write_text(json.dumps(defines, indent=2) + "\n", encoding="utf-8")
    with (generated / "ExportOptions.plist").open("wb") as output:
        plistlib.dump({"method": "app-store-connect", "destination": "export",
                      "teamID": team, "signingStyle": "automatic",
                      "manageAppVersionAndBuildNumber": False,
                      "uploadSymbols": True}, output)
    return data["ADMOB_APP_ID"]


def verify_archive(archive, mode, root=ROOT):
    info_path = Path(archive) / "Products/Applications/Runner.app/Info.plist"
    with info_path.open("rb") as source:
        info = plistlib.load(source)
    expected = TEST_APP if mode == "test" else validate_ads(json.loads(
        (root / "ios/ads.ios.local.json").read_text(encoding="utf-8-sig")))["ADMOB_APP_ID"]
    if info.get("CFBundleIdentifier") != "com.epitomehub.arrownova":
        raise ValueError("Archive bundle ID is wrong. Select the ArrowNova Runner target.")
    if info.get("GADApplicationIdentifier") != expected:
        raise ValueError("Archive AdMob App ID does not match this build mode; do not upload.")
    print("Archive verified:", info.get("CFBundleShortVersionString"),
          "build", info.get("CFBundleVersion"), "mode", mode)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["configure", "verify"])
    parser.add_argument("--mode", choices=["test", "store"], required=True)
    parser.add_argument("--team")
    parser.add_argument("--archive", default=str(ROOT / "build/ios/archive/Runner.xcarchive"))
    args = parser.parse_args()
    try:
        if args.action == "configure":
            configure(args.mode, args.team or "")
            print("Configured", args.mode, "mode. Local signing/ads files stay out of Git.")
        else:
            verify_archive(args.archive, args.mode)
    except (ValueError, OSError) as error:
        parser.exit(1, f"iOS configuration error: {error}\n")


if __name__ == "__main__":
    main()
